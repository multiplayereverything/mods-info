"""Check every mods-info file and regenerate index.json and the README's mod table.

    python tools/validate.py          check, then rewrite index.json and README.md
    python tools/validate.py --check  check only; exit 1 if a file is wrong or index/README are stale
    python tools/validate.py --test   run the validator's own tests

Standard library only. The rules match schema.json; the mods apply the same checks when they download.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ID = re.compile(r"^[a-z0-9][a-z0-9-]{0,31}$")
VERSION = re.compile(r"^[0-9]+(\.[0-9]+){0,3}$")
ADDRESS = re.compile(r"^$|^[A-Za-z0-9.-]{1,253}:[0-9]{1,5}$")
DATE = re.compile(r"^[0-9]{4}-[0-9]{2}-[0-9]{2}$")
MOD_KEYS = ["schema", "id", "name", "game", "engine", "status", "latest_version", "min_version", "protocol",
            "download_url", "changelog_url", "relay", "notice", "updated"]
TABLE_START = "<!-- mods table: generated by tools/validate.py -->"
TABLE_END = "<!-- end of mods table -->"


def version_tuple(v):
    return tuple(int(x) for x in v.split("."))


def text(errors, where, value, limit=200):
    if not isinstance(value, str) or len(value) > limit or "\n" in value:
        errors.append("%s: must be one line of text, at most %d characters" % (where, limit))


def url(errors, where, value):
    if not isinstance(value, str) or (value and not value.startswith("https://")):
        errors.append("%s: must be empty or an https:// link" % where)


def address(errors, where, value):
    ok = isinstance(value, str) and ADDRESS.match(value)
    if ok and value:
        ok = 1 <= int(value.rsplit(":", 1)[1]) <= 65535
    if not ok:
        errors.append("%s: must be empty or host:port" % where)


def check_servers(data):
    errors = []
    if not isinstance(data, dict) or data.get("schema") != 1:
        return ["servers.json: schema must be 1"]
    servers = data.get("servers")
    if not isinstance(servers, list) or not servers:
        return ["servers.json: servers must be a non-empty list"]
    seen = set()
    for i, s in enumerate(servers):
        w = "servers.json: servers[%d]" % i
        if not isinstance(s, dict):
            errors.append(w + ": must be an object")
            continue
        for k in ("id", "name", "address", "status"):
            if k not in s:
                errors.append("%s: missing %s" % (w, k))
        if not ID.match(str(s.get("id", ""))):
            errors.append(w + ": bad id")
        elif s["id"] in seen:
            errors.append(w + ": duplicate id " + s["id"])
        seen.add(s.get("id"))
        text(errors, w + ".name", s.get("name"))
        address(errors, w + ".address", s.get("address"))
        if s.get("status") not in ("online", "offline", "maintenance"):
            errors.append(w + ": status must be online, offline or maintenance")
        if s.get("status") == "online" and not s.get("address"):
            errors.append(w + ": an online server needs an address")
        if "notice" in s:
            text(errors, w + ".notice", s["notice"])
    return errors


def check_mod(name, data, server_ids):
    errors = []
    w = "mods/" + name
    if not isinstance(data, dict) or data.get("schema") != 1:
        return [w + ": schema must be 1"]
    for k in MOD_KEYS:
        if k not in data:
            errors.append("%s: missing %s" % (w, k))
    if errors:
        return errors
    if not ID.match(str(data["id"])):
        errors.append(w + ": bad id")
    elif name != data["id"] + ".json":
        errors.append("%s: file name must be %s.json" % (w, data["id"]))
    for k in ("name", "game", "engine", "protocol", "notice"):
        text(errors, "%s.%s" % (w, k), data[k])
    if data["status"] not in ("planned", "in-progress", "testing", "released"):
        errors.append(w + ": status must be planned, in-progress, testing or released")
    for k in ("latest_version", "min_version"):
        if not isinstance(data[k], str) or not VERSION.match(data[k]):
            errors.append("%s.%s: must be numbers separated by dots, like 1.2.3" % (w, k))
    if not any(e.endswith("like 1.2.3") for e in errors):
        if version_tuple(data["min_version"]) > version_tuple(data["latest_version"]):
            errors.append(w + ": min_version is above latest_version")
    for k in ("download_url", "changelog_url"):
        url(errors, "%s.%s" % (w, k), data[k])
    r = data["relay"]
    if not isinstance(r, dict):
        errors.append(w + ".relay: must be an object")
    else:
        if r.get("mode") not in ("star", "tunnel"):
            errors.append(w + ".relay.mode: must be star or tunnel")
        mp = r.get("max_players")
        if not isinstance(mp, int) or isinstance(mp, bool) or not 2 <= mp <= 16:
            errors.append(w + ".relay.max_players: must be 2 to 16")
        if r.get("server") not in server_ids:
            errors.append(w + ".relay.server: not an id in servers.json")
        if "address" in r:
            address(errors, w + ".relay.address", r["address"])
    if not isinstance(data["updated"], str) or not DATE.match(data["updated"]):
        errors.append(w + ".updated: must be YYYY-MM-DD")
    return errors


def load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def build(root):
    """Returns (errors, mods) for the repo at root."""
    errors = []
    try:
        servers = load(os.path.join(root, "servers.json"))
    except (OSError, ValueError) as e:
        return ["servers.json: " + str(e)], []
    errors += check_servers(servers)
    server_ids = {s.get("id") for s in servers.get("servers", []) if isinstance(s, dict)}
    mods = []
    folder = os.path.join(root, "mods")
    for name in sorted(os.listdir(folder)):
        if not name.endswith(".json"):
            errors.append("mods/%s: only .json files belong in mods/" % name)
            continue
        try:
            data = load(os.path.join(folder, name))
        except ValueError as e:
            errors.append("mods/%s: not valid JSON (%s)" % (name, e))
            continue
        e = check_mod(name, data, server_ids)
        errors += e
        if not e:
            mods.append(data)
    return errors, mods


def index_text(mods):
    index = {"schema": 1, "mods": [{"id": m["id"], "name": m["name"], "file": "mods/%s.json" % m["id"]} for m in mods]}
    return json.dumps(index, indent=2) + "\n"


def readme_text(old, mods):
    rows = ["| Mod | Game | Relay id | Mode | Players | Latest | Status |", "|---|---|---|---|---|---|---|"]
    for m in mods:
        rows.append("| %s | %s | [`%s`](mods/%s.json) | %s | %d | %s | %s |" % (
            m["name"], m["game"], m["id"], m["id"], m["relay"]["mode"], m["relay"]["max_players"],
            m["latest_version"], m["status"]))
    table = TABLE_START + "\n" + "\n".join(rows) + "\n" + TABLE_END
    start, end = old.find(TABLE_START), old.find(TABLE_END)
    if start < 0 or end < 0:
        raise ValueError("README.md has no generated-table markers")
    return old[:start] + table + old[end + len(TABLE_END):]


def run(root, write):
    errors, mods = build(root)
    if errors:
        for e in errors:
            print("ERROR " + e)
        return 1
    stale = []
    for name, make in (("index.json", lambda old: index_text(mods)), ("README.md", lambda old: readme_text(old, mods))):
        path = os.path.join(root, name)
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        new = make(old)
        if new != old:
            if write:
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(new)
                print("updated " + name)
            else:
                stale.append(name)
    for name in stale:
        print("ERROR %s is out of date: run python tools/validate.py" % name)
    if not stale:
        print("OK: servers.json and %d mod files (%s)" % (len(mods), ", ".join(m["id"] for m in mods)))
    return 1 if stale else 0


def self_test():
    good = {"schema": 1, "id": "demo", "name": "Demo", "game": "Demo game", "engine": "Unity", "status": "testing",
            "latest_version": "1.2.0", "min_version": "1.0", "protocol": "demo-1", "download_url": "",
            "changelog_url": "https://example.com/c", "relay": {"mode": "tunnel", "max_players": 4, "server": "main"},
            "notice": "", "updated": "2026-10-24"}
    cases = [("valid file", good, 0)]
    def bad(label, **change):
        d = json.loads(json.dumps(good))
        for k, v in change.items():
            if v is None:
                del d[k]
            else:
                d[k] = v
        cases.append((label, d, 1))
    bad("missing key", notice=None)
    bad("wrong schema", schema=2)
    bad("bad version", latest_version="1.2-beta")
    bad("min above latest", min_version="2.0")
    bad("http link", download_url="http://example.com")
    bad("unknown server", relay={"mode": "tunnel", "max_players": 4, "server": "nope"})
    bad("bad mode", relay={"mode": "udp", "max_players": 4, "server": "main"})
    bad("too many players", relay={"mode": "star", "max_players": 99, "server": "main"})
    bad("bad address", relay={"mode": "star", "max_players": 4, "server": "main", "address": "host:99999"})
    bad("two-line notice", notice="a\nb")
    bad("bad date", updated="24/10/2026")
    failed = 0
    for label, data, want_errors in cases:
        got = check_mod("demo.json", data, {"main"})
        ok = bool(got) == bool(want_errors)
        failed += not ok
        print("%s %s%s" % ("PASS" if ok else "FAIL", label, (": " + got[0]) if got else ""))
    got = check_mod("other.json", good, {"main"})
    ok = any("file name" in e for e in got); failed += not ok
    print("%s file name must match id" % ("PASS" if ok else "FAIL"))
    servers = [({"schema": 1, "servers": [{"id": "main", "name": "M", "address": "relay.example.com:25565", "status": "online"}]}, 0),
               ({"schema": 1, "servers": [{"id": "main", "name": "M", "address": "", "status": "online"}]}, 1),
               ({"schema": 1, "servers": [{"id": "main", "name": "M", "address": "", "status": "offline"}]}, 0),
               ({"schema": 1, "servers": []}, 1)]
    for data, want in servers:
        got = check_servers(data)
        ok = bool(got) == bool(want); failed += not ok
        print("%s servers.json case%s" % ("PASS" if ok else "FAIL", (": " + got[0]) if got else " (valid)"))
    total = len(cases) + 1 + len(servers)
    print("VALIDATOR TESTS %d/%d passed" % (total - failed, total))
    return 1 if failed else 0


if __name__ == "__main__":
    if "--test" in sys.argv:
        sys.exit(self_test())
    sys.exit(run(ROOT, write="--check" not in sys.argv))
